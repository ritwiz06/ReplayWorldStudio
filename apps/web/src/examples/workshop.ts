// "Try rearranging a workshop": the example world. It is made the way an uploaded drawing is: the
// API reader's analysis of fixtures/drawings/workshop-mm.dxf (a synthetic drawing made by this
// repository) goes through the same draft builder, is reviewed (floor, scale and every object
// accepted, as a person would), drawn with the in-house catalog models, and given an example
// shift. Every operating value is an example assumption, labelled as such; nothing here is a
// result, and the run, checks and comparison are computed by the app as for any project.
import type { CatalogAsset, DrawingAnalysis, Length, ProcessModel, Project, SceneObject } from "@replay-world/contracts";
import { buildDrawingProject } from "../drawing/world";

/** One entry of assets/catalog/models/manifest.json. */
export interface ManifestModel {
  name: string;
  uri: string;
  sha256: string;
  bounds_m: { min: { x: number; y: number; z: number }; max: { x: number; y: number; z: number } };
}

export const WORKSHOP_TASK = {
  /** The workstation the task is about, and the spot it is tried at (beside the doorway). */
  objectId: "obj-dxf-10a",
  spot: { x: 0.05, z: 0.95 },
} as const;

/** Which catalog model draws which drawn object (by its label in the drawing). */
const MODELS: Record<string, string> = {
  "Material rack": "storage-rack-2m",
  "Saw bench": "saw-bench",
  "Assembly bench": "assembly-workbench",
  "Packing table": "packing-table",
  "Finished goods": "pallet-cartons",
  "Electrical cabinet": "electrical-cabinet-800",
};

const IN_HOUSE_TERMS = "Original model generated by code in this repository; no third-party content. The project owner has not chosen a license.";

function catalogAsset(key: string, model: ManifestModel): CatalogAsset {
  const { min, max } = model.bounds_m;
  const extent = (value: number): Length => ({ value_m: value, origin: "user_supplied", source_ref: `Authored extent of the procedural model ${model.uri}`, review_status: "unreviewed", uncertainty_m: null });
  return {
    id: `asset-${key}`,
    name: model.name,
    kind: "equipment",
    visual: {
      type: "gltf",
      uri: model.uri,
      sha256: model.sha256,
      metres_per_model_unit: 1,
      up_axis: "+Y",
      front_axis: "+Z",
      origin: "bottom_centre",
      model_bounds_m: model.bounds_m,
      fit: "scale_to_dimensions",
      max_fit_distortion: 0.05,
      correction: null,
    },
    nominal_dimensions: { width: extent(max.x - min.x), height: extent(max.y - min.y), depth: extent(max.z - min.z) },
    source: { kind: "in_house", author: "Replay World Studio project (procedural model generator)", reference: "apps/web/scripts/catalog/models.ts" },
    rights: { license: "NOASSERTION", redistribution: "unknown", attribution: null, terms_ref: IN_HOUSE_TERMS },
    generation: null,
    upload: null,
  };
}

const example = (value: number) => ({ value, basis: "example" as const });

/** The example shift: material from the rack is cut at the saw bench, assembled at the assembly
 * bench and packed. Three workers; every value is a made-up example. */
function process(ids: Record<string, string>): ProcessModel {
  const carry = (id: string, from: string, to: string) => ({
    id,
    from_station: from,
    to_station: to,
    method: "carry" as const,
    item_width_m: example(0.6),
    allowance_m: example(0.05),
    speed_m_s: example(1),
    handling_s: example(10),
  });
  const station = (id: string, object: string, name: string, access: { x: number; z: number }, worker: number, machine: number) => ({
    id,
    object_id: ids[object]!,
    name,
    role: "process" as const,
    access_m: access,
    access_basis: "example" as const,
    worker_s: example(worker),
    machine_s: example(machine),
    input_capacity: example(1),
    output_capacity: example(1),
    planned_stops: [],
    random_stops: null,
  });
  const worker = (id: string, name: string, tasks: string[]) => ({ id, name, tasks, walk_speed_m_s: example(1.2), width_m: example(0.8) });
  return {
    format: "rws-process/1",
    name: "Example shift: cutting, assembly and packing",
    item_name: "frame",
    example_note:
      "An example to show how a layout change affects a shift. Every time, speed, break and worker assignment here is an assumption made up for this synthetic workshop: not data from a real workshop, and nothing is read from the drawing.",
    shift: {
      start_clock_s: example(7 * 3600),
      duration_s: example(8 * 3600),
      breaks: [
        { id: "break-morning", name: "Morning break", start_s: example(3 * 3600), duration_s: example(15 * 60) },
        { id: "break-lunch", name: "Lunch", start_s: example(5.5 * 3600), duration_s: example(30 * 60) },
      ],
    },
    stations: [
      { id: "rack", object_id: ids["Material rack"]!, name: "Material rack", role: "supply", access_m: { x: 0, z: 0.9 }, access_basis: "example", worker_s: null, machine_s: null, input_capacity: null, output_capacity: null, planned_stops: [], random_stops: null },
      station("saw", "Saw bench", "Saw bench", { x: 0, z: 1 }, 30, 60),
      station("assembly", "Assembly bench", "Assembly bench", { x: 0, z: -1 }, 120, 0),
      station("packing", "Packing table", "Packing table", { x: 0, z: 1 }, 60, 0),
    ],
    transfers: [carry("carry-stock", "rack", "saw"), carry("carry-cut", "saw", "assembly"), carry("carry-assembled", "assembly", "packing")],
    workers: [
      worker("worker-1", "Worker 1 (cutting)", ["transfer:carry-cut", "station:saw", "transfer:carry-stock"]),
      worker("worker-2", "Worker 2 (assembly)", ["transfer:carry-assembled", "station:assembly"]),
      worker("worker-3", "Worker 3 (packing)", ["station:packing"]),
    ],
    seed: 1,
  } as unknown as ProcessModel;
}

/** The example project, from the drawing's analysis and the catalog's manifest. */
export function workshopProject(analysis: DrawingAnalysis, manifest: readonly ManifestModel[]): Project {
  const draft = buildDrawingProject(analysis, "mm");
  const source = draft.sources[0]!;
  const review = source.drawing!.review!;
  // Reviewed as a person would: the floor, the scale from the drawing's unit, and every object.
  const reviewed = {
    ...review,
    floor: { ...review.floor, status: "accepted" as const },
    scale: { ...review.scale, status: "confirmed" as const },
    objects: review.objects.map((o) => (o.status === "proposed" ? { ...o, status: "accepted" as const } : o)),
    omissions: "accepted" as const,
  };
  const byFile = new Map(manifest.map((m) => [m.uri.replace(/^models\/|\.glb$/g, ""), m]));
  const catalog: CatalogAsset[] = [];
  const ids: Record<string, string> = {};
  const objects: SceneObject[] = draft.scene.objects.map((object) => {
    ids[object.name] = object.id;
    const key = MODELS[object.name];
    const model = key ? byFile.get(key) : undefined;
    if (!key || !model) return object;
    const asset = catalogAsset(key, model);
    catalog.push(asset);
    const height: Length = {
      value_m: asset.nominal_dimensions.height.value_m,
      origin: "default",
      source_ref: "Display height for this example: the height of the catalog model drawn for it (an illustration). Not in the drawing and not measured.",
      review_status: "unreviewed",
      uncertainty_m: null,
    };
    return { ...object, asset_id: asset.id, dimensions: { ...object.dimensions, height } };
  });
  return {
    ...draft,
    id: "proj-example-workshop",
    name: "Small workshop (example)",
    fixture: {
      kind: "demonstration",
      note: "A synthetic example: a 12 m x 8 m workshop drawn as a DXF by this repository, reviewed, drawn with in-house catalog models, and given an example shift. Not a real site; sizes are the drawing's, heights are the models' (for display), and the shift's times and workers are made-up assumptions.",
    },
    sources: [{ ...source, drawing: { ...source.drawing!, review: reviewed } }],
    catalog,
    scene: { ...draft.scene, id: "scene-example-workshop", name: "Small workshop (example)", objects },
    process: process(ids),
  };
}
