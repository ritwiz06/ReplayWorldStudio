"""Build fixtures/scenes/industrial-demo.json from the catalog model manifest.

    uv run python scripts/build_demo_fixture.py           write the fixture
    uv run python scripts/build_demo_fixture.py --check   fail if the committed file is stale

The scene is a synthetic demonstration of a small packaging line. Every value is illustrative;
the glTF hashes and bounds are copied from assets/catalog/models/manifest.json so the fixture
always names the exact model files in the repository.
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path
from typing import Any, Final

from replay_world_contracts import Project

ROOT: Final = Path(__file__).resolve().parents[1]
MANIFEST: Final = ROOT / "assets" / "catalog" / "models" / "manifest.json"
OUTPUT: Final = ROOT / "fixtures" / "scenes" / "industrial-demo.json"

LAYOUT_REF: Final = "Synthetic demonstration layout (scripts/build_demo_fixture.py)"
MAX_FIT_DISTORTION: Final = 0.05


def length(value: float, ref: str) -> dict[str, Any]:
    return {
        "value_m": value,
        "origin": "user_supplied",
        "source_ref": ref,
        "review_status": "unreviewed",
        "uncertainty_m": None,
    }


def dims(width: float, height: float, depth: float, ref: str = LAYOUT_REF) -> dict[str, Any]:
    return {"width": length(width, ref), "height": length(height, ref), "depth": length(depth, ref)}


def transform(x: float, z: float, y: float = 0.0, yaw: float = 0.0) -> dict[str, Any]:
    return {
        "position_m": {"x": x, "y": y, "z": z},
        "rotation_rad": {"order": "XYZ", "x": 0.0, "y": yaw, "z": 0.0},
    }


def extents(model: dict[str, Any]) -> tuple[float, float, float]:
    lo, hi = model["bounds_m"]["min"], model["bounds_m"]["max"]
    width, height, depth = (round(hi[a] - lo[a], 4) for a in "xyz")
    return width, height, depth


def catalog_asset(asset_id: str, name: str, model: dict[str, Any]) -> dict[str, Any]:
    width, height, depth = extents(model)
    return {
        "id": asset_id,
        "name": name,
        "kind": "equipment",
        "visual": {
            "type": "gltf",
            "uri": model["uri"],
            "sha256": model["sha256"],
            "metres_per_model_unit": 1.0,
            "up_axis": "+Y",
            "front_axis": "+Z",
            "origin": "bottom_centre",
            "model_bounds_m": model["bounds_m"],
            "fit": "scale_to_dimensions",
            "max_fit_distortion": MAX_FIT_DISTORTION,
        },
        "nominal_dimensions": dims(
            width, height, depth, f"Authored extent of the procedural model {model['uri']}"
        ),
        "source": {
            "kind": "in_house",
            "author": "Replay World Studio project (procedural model generator)",
            "reference": "apps/web/scripts/catalog/models.ts",
        },
        "rights": {
            "license": "NOASSERTION",
            "redistribution": "unknown",
            "attribution": None,
            "terms_ref": (
                "Original model generated by code in this repository; no third-party content. "
                "The project owner has not chosen a license."
            ),
        },
    }


def equipment(
    object_id: str,
    name: str,
    asset: dict[str, Any],
    x: float,
    z: float,
    parameters: list[dict[str, Any]],
    yaw: float = 0.0,
) -> dict[str, Any]:
    nominal = asset["nominal_dimensions"]
    ref = f"Catalog nominal of {asset['id']} (synthetic demonstration)"
    return {
        "id": object_id,
        "name": name,
        "kind": "equipment",
        "asset_id": asset["id"],
        "transform": transform(x, z, yaw=yaw),
        "dimensions": dims(
            nominal["width"]["value_m"],
            nominal["height"]["value_m"],
            nominal["depth"]["value_m"],
            ref,
        ),
        "parameters": parameters,
    }


def geometry(
    object_id: str,
    name: str,
    kind: str,
    x: float,
    z: float,
    size: tuple[float, float, float],
    y: float = 0.0,
) -> dict[str, Any]:
    return {
        "id": object_id,
        "name": name,
        "kind": kind,
        "asset_id": None,
        "transform": transform(x, z, y=y),
        "dimensions": dims(*size),
        "parameters": [],
    }


def unknown(param_id: str, label: str, unit: str, reason: str) -> dict[str, Any]:
    return {"state": "unknown", "id": param_id, "label": label, "unit": unit, "reason": reason}


def known(param_id: str, label: str, unit: str, value: float) -> dict[str, Any]:
    return {
        "state": "known",
        "id": param_id,
        "label": label,
        "unit": unit,
        "value": value,
        "origin": "user_supplied",
        "source_ref": "Illustrative value for the synthetic demonstration",
        "review_status": "unreviewed",
        "uncertainty": None,
    }


def build() -> Project:
    models = {m["key"]: m for m in json.loads(MANIFEST.read_text())["models"]}
    conveyor = catalog_asset(
        "asset-belt-conveyor-3m", "Belt conveyor, 3 m", models["belt-conveyor-3m"]
    )
    cell = catalog_asset(
        "asset-guarded-machine-cell", "Guarded machine cell", models["guarded-machine-cell"]
    )
    cabinet = catalog_asset(
        "asset-electrical-cabinet-800",
        "Electrical cabinet, 800 mm",
        models["electrical-cabinet-800"],
    )
    pallet = catalog_asset("asset-pallet-cartons", "Pallet with cartons", models["pallet-cartons"])

    line_z = -1.2  # centre line of the packaging line (product flows towards +X)
    conveyor_w = conveyor["nominal_dimensions"]["width"]["value_m"]
    cell_w = cell["nominal_dimensions"]["width"]["value_m"]
    cabinet_w = cabinet["nominal_dimensions"]["width"]["value_m"]
    cabinet_d = cabinet["nominal_dimensions"]["depth"]["value_m"]
    wall_face_z = -7.3

    # Lay the line out end to end from the infeed at x = -9.2 m.
    x = -9.2
    centres = []
    for w in (conveyor_w, cell_w, conveyor_w, cell_w, conveyor_w):
        centres.append(round(x + w / 2, 4))
        x += w
    belt = known("belt-speed", "Belt speed", "m/s", 0.3)
    cycle = unknown(
        "cycle-time", "Cycle time", "s", "Not specified for the synthetic demonstration"
    )
    cabinet_z = round(wall_face_z + cabinet_d / 2, 4)

    objects = [
        geometry("obj-floor", "Floor slab", "structure", 0.0, 0.0, (22.0, 0.2, 15.0), y=-0.2),
        geometry("obj-wall-north", "North wall", "structure", 0.0, -7.4, (22.0, 5.0, 0.2)),
        geometry("obj-column-b1", "Column B1", "structure", -5.5, -4.6, (0.45, 5.0, 0.45)),
        geometry("obj-column-b2", "Column B2", "structure", 5.5, -4.6, (0.45, 5.0, 0.45)),
        equipment("obj-conveyor-infeed", "Infeed conveyor", conveyor, centres[0], line_z, [belt]),
        equipment("obj-cell-filling", "Filling cell", cell, centres[1], line_z, [cycle]),
        equipment(
            "obj-conveyor-transfer", "Transfer conveyor", conveyor, centres[2], line_z, [belt]
        ),
        equipment("obj-cell-inspection", "Inspection cell", cell, centres[3], line_z, [cycle]),
        equipment("obj-conveyor-outfeed", "Outfeed conveyor", conveyor, centres[4], line_z, [belt]),
        equipment("obj-pallet-outfeed", "Outfeed pallet", pallet, 5.6, line_z, []),
        equipment(
            "obj-pallet-staged", "Staged pallet", pallet, 8.4, 4.2, [], yaw=round(math.pi / 2, 12)
        ),
        equipment("obj-cabinet-1", "Control cabinet 1", cabinet, -2.0, cabinet_z, []),
        equipment("obj-cabinet-2", "Control cabinet 2", cabinet, -2.0 + cabinet_w, cabinet_z, []),
        geometry("obj-walkway-main", "Main walkway", "walkway", 0.0, 1.5, (21.0, 0.003, 1.8)),
        geometry(
            "obj-keep-clear-cabinets",
            "Cabinet access - keep clear",
            "keep_clear",
            -1.6,
            round(wall_face_z + cabinet_d + 0.5, 4),
            (2.0, 0.003, 1.0),
        ),
    ]
    document = {
        "schema_version": "0.3.0",
        "id": "proj-industrial-demo",
        "name": "Industrial demo - packaging line (synthetic)",
        "units": {"length": "m", "time": "s", "mass": "kg", "angle": "rad"},
        "world_frame": {"handedness": "right", "up_axis": "+Y", "floor_plane": "XZ"},
        "fixture": {
            "kind": "demonstration",
            "note": (
                "Synthetic demonstration of a small packaging line. The layout, sizes and "
                "parameters are illustrative, and the equipment models are original, simplified "
                "illustrations - not verified engineering data or real products."
            ),
        },
        "sources": [],
        "catalog": [conveyor, cell, cabinet, pallet],
        "scene": {
            "id": "scene-industrial-demo",
            "name": "Packaging line (synthetic demonstration)",
            "revision": 0,
            "objects": objects,
        },
    }
    return Project.model_validate(document)


def render() -> str:
    return build().model_dump_json(indent=2) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print(f"Out of date: {OUTPUT.relative_to(ROOT)}. Run `pnpm fixtures:build`.")
            return 1
        print("Industrial demo fixture is up to date.")
        return 0
    OUTPUT.write_text(text)
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
